import datetime as dt
import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from engine import Game, Hunt, norm  # noqa: E402

HUNT = Hunt(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "hunt.yaml"))
TZ = HUNT.tz


class Mail:
    def __init__(self):
        self.sent = []

    def send(self, to, subject, body, in_reply_to=None):
        self.sent.append((to, subject, body))


class FakeLLM:
    def classify(self, st, text):
        return "wrong"

    def make_clue(self, st, prev, n):
        return f"generated clue {n}"


class Clock:
    def __init__(self, y=2026, mo=11, d=14, h=8, mi=0):
        self.t = dt.datetime(y, mo, d, h, mi, tzinfo=TZ)

    def __call__(self):
        return self.t

    def to(self, h, mi=0):
        self.t = self.t.replace(hour=h, minute=mi)

    def add(self, minutes):
        self.t += dt.timedelta(minutes=minutes)


def make(tmp_path, mode, clock=None, llm=None):
    clock = clock or Clock()
    mail = Mail()
    g = Game(str(tmp_path / "t.db"), HUNT, llm=llm, mailer=mail, now_fn=clock,
             cfg={"mode": mode, "player_test": "me@x.com", "player_live": "her@x.com", "admin_email": "me@x.com"})
    return g, mail, clock


def say(g, text, i=[0]):
    i[0] += 1
    r = g.handle_inbound(text, f"<m{i[0]}@t>")
    g.tick()
    return r


def count(mail):
    return len([m for m in mail.sent if 'Hunt status' not in m[1]])


def last(mail):
    return [m for m in mail.sent if 'Hunt status' not in m[1]][-1][2]


def test_norm_and_short_answer(tmp_path):
    g, mail, _ = make(tmp_path, "TEST")
    g.send_opening(); g.tick()
    assert "[TEST]" in mail.sent[0][1]
    say(g, "Let games begin")           # no "the"
    assert "Riddle 1" in last(mail)
    say(g, "flowers!!")
    assert "Riddle 2" in last(mail) and "Gift unlocked: flowers" in last(mail)  # no gate in TEST
    say(g, "I have no clue what you mean, nu ai spus")  # clue request, 'ai' must not match
    assert last(mail).startswith("Clue 1")


def test_clue_bank_then_llm_then_fallback(tmp_path):
    g, mail, _ = make(tmp_path, "TEST", llm=FakeLLM())
    g.send_opening(); say(g, "let the games begin")
    for n in range(1, 4):
        say(g, "clue")
        assert last(mail).startswith(f"Clue {n}")
    say(g, "a lamp?")                    # wrong -> 4th clue generated by the LLM
    assert "generated clue 4" in last(mail)
    assert g.state["generated"]["flowers"] == ["generated clue 4"]
    g.llm = None
    say(g, "clue")
    assert "letters" in last(mail) or "starts with" in last(mail)


def test_full_test_run_and_dedupe(tmp_path):
    g, mail, _ = make(tmp_path, "TEST")
    g.send_opening(); say(g, "let the games begin")
    answers = ["bouquet", "PFA", "bbq with salad", "Team Building 2", "a website", "strap on",
               "a swing", "xbox", "dermapen", "handbag", "Claude and ChatGPT", "a book", "Strada Decebal 12", "El Torito"]
    for a in answers:
        say(g, a)
    assert g.state["finished"]
    assert "El Torito Legacy" in last(mail)
    g.handle_inbound("x", "<dup@t>")
    assert g.handle_inbound("x", "<dup@t>") == "duplicate"


def test_live_gates_blackout_deadlines(tmp_path):
    g, mail, clock = make(tmp_path, "LIVE")
    g.tick()
    assert not mail.sent                     # before 08:30
    clock.to(8, 30); g.tick()
    assert "Happy birthday" in mail.sent[0][2] and "[TEST]" not in mail.sent[0][1]
    clock.to(9, 0); say(g, "let the games begin")
    say(g, "flowers")
    assert "arrives at 11:00" in last(mail)
    n = len(mail.sent)
    clock.to(10, 59); g.tick(); assert len(mail.sent) == n
    clock.to(11, 0); g.tick(); assert "Riddle 2" in last(mail)
    say(g, "pfa")                             # lunch gated until 12:00
    assert "arrives at 12:00" in last(mail)
    clock.to(12, 0); g.tick(); assert "Lunch check-in" in last(mail)
    clock.to(12, 21); g.tick()                # lunch deadline 12:20 -> cinema riddle
    assert "Riddle 3" in last(mail) and "barbecue" in last(mail)
    clock.to(13, 1); g.tick(); assert last(mail).startswith("Clue")   # fast clues from 13:00
    clock.to(13, 21); g.tick()                # cinema deadline
    assert "get ready" in last(mail) or "Riddle 4" in last(mail)
    assert g.stage()["id"] == "web"
    clock.to(13, 50); n = count(mail); say(g, "website")   # blackout: held
    assert count(mail) == n
    clock.to(16, 44); g.tick(); assert count(mail) == n
    clock.to(16, 45); g.tick(); assert "Riddle 5" in last(mail)


def test_nudges(tmp_path):
    g, mail, clock = make(tmp_path, "LIVE", clock=Clock(h=9, mi=0))
    g.state["mode"] = "LIVE"
    g.send_opening(); g.tick()
    say(g, "let the games begin")
    n = len(mail.sent)
    clock.add(29); g.tick(); assert len(mail.sent) == n
    clock.add(2); g.tick(); assert "Reply CLUE" in last(mail)         # offer at 30
    clock.add(30); g.tick(); assert last(mail).startswith("Clue 1")   # unasked clue at 60
    clock.add(41); g.tick(); assert last(mail).startswith("Clue 2")   # every 40


def test_bundle_and_dinner(tmp_path):
    g, mail, clock = make(tmp_path, "LIVE", clock=Clock(h=19, mi=0))
    g.send_opening(); g.tick()
    g.state["idx"] = HUNT.index["swing"]; g.state["sent"]["swing"] = True
    clock.to(19, 31); g.tick()
    assert any("all the gifts" in m[2] for m in mail.sent)
    assert g.stage()["id"] == "address"
    clock.to(20, 46); g.tick()
    assert g.state["finished"] and "El Torito Legacy" in last(mail)
